// Regenerates lib/licenses.generated.ts from the installed production dependencies.
// Run: node scripts/gen-licenses.mjs
import { readFileSync, writeFileSync } from "node:fs";

const pkg = JSON.parse(readFileSync("package.json", "utf8"));
const rows = Object.keys(pkg.dependencies)
  .sort()
  .map((name) => {
    const p = JSON.parse(readFileSync(`node_modules/${name}/package.json`, "utf8"));
    const repo = typeof p.repository === "string" ? p.repository : p.repository?.url;
    const url = (p.homepage || repo || `https://www.npmjs.com/package/${name}`)
      .replace(/^git\+/, "")
      .replace(/\.git$/, "")
      .replace(/^git:\/\//, "https://");
    return { name, version: p.version, license: p.license ?? "See package", url };
  });

writeFileSync(
  "lib/licenses.generated.ts",
  `// Generated by scripts/gen-licenses.mjs. Do not edit by hand.\nexport const LICENSES = ${JSON.stringify(rows, null, 2)} as const;\n`,
);
console.log(rows.map((r) => `${r.name}@${r.version} ${r.license}`).join("\n"));
